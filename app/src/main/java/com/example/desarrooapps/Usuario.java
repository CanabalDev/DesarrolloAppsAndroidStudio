package com.example.desarrooapps;

final class Usuario {
    final String id;
    final String nombreUsuario;
    final String nombre;
    final String correo;

    Usuario(String id, String nombreUsuario, String nombre, String correo) {
        this.id = id;
        this.nombreUsuario = nombreUsuario;
        this.nombre = nombre;
        this.correo = correo;
    }
}
